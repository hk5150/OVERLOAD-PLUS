// 記録の種目から、塗る部位の Set を作る(index.html にグラフ用の trainedMuscles があるので名前を分けた)。norm は部位名の正規化(index.html の normMuscle。旧名「胸」→「大胸筋」など)。
// ウォームアップだけの種目は鍛えた数に入れない。「全身」は特定の部位が無いので塗らない
function bodyHitMuscles(exercises, norm) {
  const out = new Set();
  for (const ex of exercises || []) {
    if (!ex) continue;
    const sets = ex.sets || [];
    if (sets.length > 0 && sets.every(s => s && s.warmup)) continue;
    const m = norm ? norm(ex.muscle) : ex.muscle;
    if (m && m !== "全身" && Object.prototype.hasOwnProperty.call(BODY_REGIONS, m)) out.add(m);
  }
  return out;
}

