// x を 100 で折り返す(左半身 → 右半身)
function mirrorBodyPath(d) {
  return String(d).replace(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g, (_, x, y) => `${+(100 - parseFloat(x)).toFixed(2)},${y}`);
}

